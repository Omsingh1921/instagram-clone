import React, { createContext, useContext, useState, useEffect, useRef, useCallback } from 'react';
import stompClient from '../services/websocket';
import webrtcService from '../services/webrtc.service';
import callService from '../services/call.service';
import { useAuth } from './AuthContext';
import { useToast } from './ToastContext';

export const CallContext = createContext(null);

export const CallProvider = ({ children }) => {
  const { user: currentUser } = useAuth();
  const { showSuccess, showError } = useToast();

  const [incomingCall, setIncomingCall] = useState(null);
  const [activeCall, setActiveCall] = useState(null);
  const [localStream, setLocalStream] = useState(null);
  const [remoteStream, setRemoteStream] = useState(null);
  const [remoteStreams, setRemoteStreams] = useState({});
  const [groupParticipants, setGroupParticipants] = useState([]);
  const [isMuted, setIsMuted] = useState(false);
  const [isVideoOff, setIsVideoOff] = useState(false);
  const [isScreenSharing, setIsScreenSharing] = useState(false);
  const [callDuration, setCallDuration] = useState(0);
  const [isMinimized, setIsMinimized] = useState(false);
  const [callStatusText, setCallStatusText] = useState('');

  const currentUserId = currentUser?.id || currentUser?.userId;
  const timerRef = useRef(null);
  const ringingTimeoutRef = useRef(null);
  const pendingOfferRef = useRef(null);
  const activeCallRef = useRef(null);
  activeCallRef.current = activeCall;

  const showErrorRef = useRef(showError);
  showErrorRef.current = showError;
  const showSuccessRef = useRef(showSuccess);
  showSuccessRef.current = showSuccess;

  // Cleanup helper
  const cleanupCallState = useCallback(() => {
    webrtcService.closePeerConnection();
    if (timerRef.current) {
      clearInterval(timerRef.current);
      timerRef.current = null;
    }
    if (ringingTimeoutRef.current) {
      clearTimeout(ringingTimeoutRef.current);
      ringingTimeoutRef.current = null;
    }
    setIncomingCall(null);
    setActiveCall(null);
    setLocalStream(null);
    setRemoteStream(null);
    setRemoteStreams({});
    setGroupParticipants([]);
    setIsMuted(false);
    setIsVideoOff(false);
    setIsScreenSharing(false);
    setCallDuration(0);
    setIsMinimized(false);
    setCallStatusText('');
    pendingOfferRef.current = null;
  }, []);

  // WebRTC Signal Sender Helper
  const sendSignal = useCallback((callId, recipientId, signalType, data) => {
    console.log(`[CallContext] Sending signal: ${signalType} to ${recipientId} (call: ${callId})`);
    stompClient.send('/app/call/signal', {
      callId,
      recipientId,
      signalType,
      data,
    });
  }, []);

  // Handle ICE Candidate generated by local browser
  const handleLocalIceCandidate = useCallback((candidate) => {
    const current = activeCallRef.current;
    if (!current) return;
    const targetUserId = current.isCaller
      ? (current.recipient?.id || current.recipient?.userId)
      : (current.caller?.id || current.caller?.userId);

    if (targetUserId) {
      sendSignal(current.callId, targetUserId, 'ice-candidate', candidate);
    }
  }, [sendSignal]);

  // Handle Remote Media Stream received
  const handleRemoteStream = useCallback((stream) => {
    console.log('[CallContext] Remote stream received:', stream, 'tracks:', stream?.getTracks?.());
    setRemoteStream(stream);
    if (stream) {
      stream.onaddtrack = () => {
        console.log('[CallContext] Remote track added dynamically');
        setRemoteStream(new MediaStream(stream.getTracks()));
      };
      stream.onremovetrack = () => {
        setRemoteStream(new MediaStream(stream.getTracks()));
      };
    }
  }, []);

  // Handle Connection State Change
  const handleConnectionStateChange = useCallback((state) => {
    console.log('[CallContext] Connection state changed:', state);
    if (state === 'connected') {
      setCallStatusText('Connected');
      if (!timerRef.current) {
        timerRef.current = setInterval(() => {
          setCallDuration((prev) => prev + 1);
        }, 1000);
      }
    } else if (state === 'disconnected' || state === 'failed') {
      setCallStatusText('Disconnected');
    }
  }, []);

  // Start Call (Caller flow)
  const startCall = useCallback(async (recipient, callType = 'VIDEO', conversationId = null) => {
    if (!recipient || !recipient.id) {
      showError('Please select a valid user to call');
      return;
    }

    try {
      setCallStatusText('Calling...');
      setIsMinimized(false);

      // 1. Acquire local camera/mic
      const stream = await webrtcService.getLocalMedia(callType);
      setLocalStream(stream);

      // 2. Setup RTCPeerConnection
      webrtcService.createPeerConnection(
        handleLocalIceCandidate,
        handleRemoteStream,
        handleConnectionStateChange
      );

      // 3. Initiate call via backend API
      const res = await callService.initiateCall(recipient.id, callType, conversationId);
      const callData = res.data || res;

      if (callData.status === 'BUSY') {
        showError(callData.reason || 'User is busy on another call');
        cleanupCallState();
        return;
      }

      setActiveCall({
        callId: callData.id,
        conversationId,
        recipient,
        caller: currentUser,
        callType,
        isCaller: true,
      });

      setCallStatusText('Ringing...');

      // Auto-cancel call if no answer within 45s
      if (ringingTimeoutRef.current) clearTimeout(ringingTimeoutRef.current);
      ringingTimeoutRef.current = setTimeout(async () => {
        if (activeCallRef.current && activeCallRef.current.callId === callData.id) {
          showErrorRef.current?.('User did not answer');
          try {
            await callService.endCall(callData.id);
          } catch {
            // ignore
          }
          cleanupCallState();
        }
      }, 45000);
    } catch (err) {
      console.error('[CallContext] Failed to start call:', err);
      showError(err.message || 'Failed to start call. Please check microphone/camera permissions.');
      cleanupCallState();
    }
  }, [currentUser, handleLocalIceCandidate, handleRemoteStream, handleConnectionStateChange, showError, cleanupCallState]);

  // Start Group Call (Audio or Video)
  const startGroupCall = useCallback(async (conversation, callType = 'VIDEO') => {
    if (!conversation || !conversation.id) {
      showError('Please select a valid group conversation');
      return;
    }

    try {
      setCallStatusText('Starting group call...');
      setIsMinimized(false);

      const stream = await webrtcService.getLocalMedia(callType);
      setLocalStream(stream);

      const res = await callService.initiateGroupCall(conversation.id, callType);
      const callData = res.data || res;

      const mySummary = {
        id: currentUserId,
        userId: currentUserId,
        username: currentUser?.username,
        displayName: currentUser?.displayName || currentUser?.fullName || currentUser?.username,
        avatarUrl: currentUser?.avatarUrl || currentUser?.profilePictureUrl,
      };

      const initialParticipants = callData.participants && callData.participants.length > 0
        ? callData.participants
        : [mySummary];

      setActiveCall({
        callId: callData.id,
        conversationId: conversation.id,
        isGroup: true,
        groupName: conversation.name || 'Group Call',
        groupAvatarUrl: conversation.avatarUrl,
        caller: currentUser,
        callType,
        isCaller: true,
        participants: initialParticipants,
      });
      setGroupParticipants(initialParticipants);
      setCallStatusText('In call');

      if (!timerRef.current) {
        timerRef.current = setInterval(() => {
          setCallDuration((prev) => prev + 1);
        }, 1000);
      }
    } catch (err) {
      console.error('[CallContext] Failed to start group call:', err);
      showError(err.message || 'Failed to start group call. Please check microphone/camera permissions.');
      cleanupCallState();
    }
  }, [currentUser, currentUserId, showError, cleanupCallState]);

  // Accept Call (Callee flow - supports both 1:1 and Group Calls)
  const acceptCall = useCallback(async () => {
    if (!incomingCall) return;

    try {
      webrtcService.stopRingtone();
      setCallStatusText('Connecting...');
      const callType = incomingCall.callType || 'VIDEO';

      // 1. Acquire local camera/mic
      const stream = await webrtcService.getLocalMedia(callType);
      setLocalStream(stream);

      // Group Call flow
      if (incomingCall.isGroup) {
        const res = await callService.joinCall(incomingCall.callId);
        const callData = res.data || res;

        const mySummary = {
          id: currentUserId,
          userId: currentUserId,
          username: currentUser?.username,
          displayName: currentUser?.displayName || currentUser?.fullName || currentUser?.username,
          avatarUrl: currentUser?.avatarUrl || currentUser?.profilePictureUrl,
        };

        const existingList = (callData.participants && callData.participants.length > 0)
          ? callData.participants
          : (incomingCall.participants || []);

        const dedupedList = existingList.some((p) => (p.id || p.userId) === currentUserId)
          ? existingList
          : [...existingList, mySummary];

        setActiveCall({
          callId: incomingCall.callId,
          conversationId: incomingCall.conversationId,
          isGroup: true,
          groupName: incomingCall.groupName || 'Group Call',
          groupAvatarUrl: incomingCall.groupAvatarUrl,
          caller: incomingCall.caller,
          callType,
          isCaller: false,
          participants: dedupedList,
        });
        setGroupParticipants(dedupedList);
        setIncomingCall(null);
        setCallStatusText('Connected');

        if (!timerRef.current) {
          timerRef.current = setInterval(() => {
            setCallDuration((prev) => prev + 1);
          }, 1000);
        }

        // Establish WebRTC mesh connections to all members already in the call
        for (const peer of existingList) {
          const peerId = peer.id || peer.userId;
          if (peerId && peerId !== currentUserId) {
            try {
              webrtcService.createPeerForUser(
                peerId,
                (targetId, candidate) => sendSignal(incomingCall.callId, targetId, 'ice-candidate', candidate),
                (targetId, rStream) => setRemoteStreams((prev) => ({ ...prev, [targetId]: rStream })),
                (targetId, state) => console.log(`[GroupCall] Peer ${targetId} state:`, state)
              );
              const offer = await webrtcService.createOfferForUser(peerId);
              sendSignal(incomingCall.callId, peerId, 'offer', offer);
            } catch (e) {
              console.warn('[GroupCall] Peer connection notice:', e);
            }
          }
        }
        return;
      }

      // 1:1 Direct Call flow
      webrtcService.createPeerConnection(
        handleLocalIceCandidate,
        handleRemoteStream,
        handleConnectionStateChange
      );

      // Inform backend via REST/STOMP
      await callService.answerCall(incomingCall.callId);

      const ongoing = {
        callId: incomingCall.callId,
        conversationId: incomingCall.conversationId,
        caller: incomingCall.caller,
        recipient: currentUser,
        callType,
        isCaller: false,
      };
      setActiveCall(ongoing);
      setIncomingCall(null);

      // If an SDP offer was already queued, process it and send answer back
      if (pendingOfferRef.current) {
        const answer = await webrtcService.handleOfferAndCreateAnswer(pendingOfferRef.current);
        const callerId = incomingCall.caller?.id || incomingCall.caller?.userId;
        sendSignal(incomingCall.callId, callerId, 'answer', answer);
        pendingOfferRef.current = null;
      }
    } catch (err) {
      console.error('[CallContext] Failed to accept call:', err);
      showError('Failed to connect call: ' + (err.message || 'Unknown error'));
      cleanupCallState();
    }
  }, [incomingCall, currentUser, currentUserId, handleLocalIceCandidate, handleRemoteStream, handleConnectionStateChange, sendSignal, showError, cleanupCallState]);

  // Reject / Decline incoming call
  const rejectCall = useCallback(async () => {
    if (!incomingCall) return;
    webrtcService.stopRingtone();
    try {
      await callService.rejectCall(incomingCall.callId);
    } catch (e) {
      console.warn('[CallContext] Reject call API notice:', e);
    }
    setIncomingCall(null);
  }, [incomingCall]);

  // End active call (or Leave if group call)
  const endCall = useCallback(async () => {
    const current = activeCall;
    if (current?.callId) {
      try {
        if (current.isGroup) {
          await callService.leaveCall(current.callId);
        } else {
          await callService.endCall(current.callId);
        }
      } catch (e) {
        console.warn('[CallContext] End/Leave call notice:', e);
      }
    }
    cleanupCallState();
  }, [activeCall, cleanupCallState]);

  // Toggle Microphone
  const toggleMute = useCallback(() => {
    const enabled = webrtcService.toggleAudio();
    setIsMuted(!enabled);
  }, []);

  // Toggle Camera
  const toggleVideo = useCallback(async () => {
    const stream = webrtcService.localStream;
    const videoTracks = stream ? stream.getVideoTracks() : [];

    if (videoTracks.length > 0) {
      const enabled = webrtcService.toggleVideo();
      setIsVideoOff(!enabled);
    } else if (webrtcService.peerConnection) {
      try {
        const videoStream = await navigator.mediaDevices.getUserMedia({
          video: { width: { ideal: 1280 }, height: { ideal: 720 }, facingMode: 'user' },
        });
        const newTrack = videoStream.getVideoTracks()[0];
        if (newTrack) {
          if (stream) {
            stream.addTrack(newTrack);
          }
          webrtcService.peerConnection.addTrack(newTrack, stream || videoStream);
          setLocalStream(new MediaStream(stream ? stream.getTracks() : videoStream.getTracks()));
          setIsVideoOff(false);
        }
      } catch (err) {
        console.warn('[CallContext] Could not turn on camera:', err);
        showErrorRef.current?.('Could not access camera. Please check permissions.');
      }
    }
  }, []);

  // Toggle Screen Sharing
  const toggleScreenShare = useCallback(async () => {
    if (isScreenSharing) {
      await webrtcService.stopScreenShare();
      setIsScreenSharing(false);
    } else {
      const stream = await webrtcService.startScreenShare();
      if (stream) {
        setIsScreenSharing(true);
      }
    }
  }, [isScreenSharing]);

  // Toggle Minimize (Picture-in-picture dock)
  const toggleMinimize = useCallback(() => {
    setIsMinimized((prev) => !prev);
  }, []);

  // STOMP WebSocket Listener for incoming calls & signaling
  useEffect(() => {
    if (!currentUserId) return;

    const topic = `/topic/users/${currentUserId}/call`;
    const unsubscribe = stompClient.subscribe(topic, async (msg) => {
      if (!msg || !msg.eventType) return;
      console.log('[CallContext] Received call event:', msg.eventType, msg);

      switch (msg.eventType) {
        case 'INCOMING_CALL': {
          if (activeCallRef.current) {
            // User is busy in another call
            stompClient.send('/app/call/reject', { callId: msg.callId });
            return;
          }
          setIncomingCall({
            callId: msg.callId,
            conversationId: msg.conversationId,
            caller: msg.caller,
            callType: msg.callType,
            isGroup: !!msg.isGroup,
            groupName: msg.groupName,
            groupAvatarUrl: msg.groupAvatarUrl,
            participants: msg.participants || [],
          });
          webrtcService.playRingtone();
          if (ringingTimeoutRef.current) clearTimeout(ringingTimeoutRef.current);
          ringingTimeoutRef.current = setTimeout(() => {
            webrtcService.stopRingtone();
            setIncomingCall((prev) => (prev?.callId === msg.callId ? null : prev));
          }, 45000);
          break;
        }

        case 'PARTICIPANT_JOINED': {
          console.log('[CallContext] Participant joined group call:', msg.participant);
          const joinedUser = msg.participant;
          const joinedUserId = joinedUser?.id || joinedUser?.userId;

          if (joinedUserId && joinedUserId !== currentUserId) {
            setGroupParticipants((prev) => {
              const exists = prev.some((p) => (p.id || p.userId) === joinedUserId);
              return exists ? prev : [...prev, joinedUser];
            });

            // When an active group member sees a new peer join, initiate WebRTC connection
            if (activeCallRef.current?.isGroup) {
              try {
                webrtcService.createPeerForUser(
                  joinedUserId,
                  (targetId, candidate) => sendSignal(msg.callId, targetId, 'ice-candidate', candidate),
                  (targetId, rStream) => setRemoteStreams((prev) => ({ ...prev, [targetId]: rStream })),
                  (targetId, state) => console.log(`[GroupCall] Peer ${targetId} state:`, state)
                );
                webrtcService.createOfferForUser(joinedUserId).then((offer) => {
                  sendSignal(msg.callId, joinedUserId, 'offer', offer);
                }).catch((e) => {
                  console.warn('[CallContext] Error creating offer for joined peer:', e);
                });
              } catch (e) {
                console.warn('[CallContext] Failed to setup peer for joined user:', e);
              }
            }
          }
          break;
        }

        case 'PARTICIPANT_LEFT': {
          console.log('[CallContext] Participant left group call:', msg.participant);
          const leftUserId = msg.participant?.id || msg.participant?.userId;
          if (leftUserId) {
            webrtcService.closePeer(leftUserId);
            setRemoteStreams((prev) => {
              const copy = { ...prev };
              delete copy[leftUserId];
              return copy;
            });
            setGroupParticipants((prev) => prev.filter((p) => (p.id || p.userId) !== leftUserId));
          }
          break;
        }

        case 'CALL_ACCEPTED': {
          if (ringingTimeoutRef.current) {
            clearTimeout(ringingTimeoutRef.current);
            ringingTimeoutRef.current = null;
          }
          // Caller receives this: create SDP Offer and send to Callee
          setCallStatusText('Connecting...');
          try {
            const offer = await webrtcService.createOffer();
            const recipientId = msg.recipient?.id || msg.recipient?.userId;
            sendSignal(msg.callId, recipientId, 'offer', offer);
          } catch (e) {
            console.error('[CallContext] Failed to create offer:', e);
          }
          break;
        }

        case 'CALL_REJECTED': {
          webrtcService.stopRingtone();
          showErrorRef.current?.(msg.reason || 'Call was declined');
          cleanupCallState();
          break;
        }

        case 'CALL_ENDED': {
          showSuccessRef.current?.(`Call ended (${msg.durationSeconds || 0}s)`);
          cleanupCallState();
          break;
        }

        case 'CALL_BUSY': {
          showErrorRef.current?.('User is busy on another call');
          cleanupCallState();
          break;
        }

        case 'SIGNAL': {
          const { signalType, signalData } = msg;
          const peerId = msg.caller?.id || msg.caller?.userId;

          // Multi-peer group call signaling
          if (activeCallRef.current?.isGroup && peerId) {
            if (signalType === 'offer') {
              try {
                webrtcService.createPeerForUser(
                  peerId,
                  (targetId, candidate) => sendSignal(msg.callId, targetId, 'ice-candidate', candidate),
                  (targetId, rStream) => setRemoteStreams((prev) => ({ ...prev, [targetId]: rStream })),
                  (targetId, state) => console.log(`[GroupCall] Peer ${targetId} state:`, state)
                );
                const answer = await webrtcService.handleOfferAndCreateAnswerForUser(peerId, signalData);
                sendSignal(msg.callId, peerId, 'answer', answer);
              } catch (e) {
                console.error('[CallContext] Failed to handle group offer:', e);
              }
            } else if (signalType === 'answer') {
              await webrtcService.handleAnswerForUser(peerId, signalData);
            } else if (signalType === 'ice-candidate') {
              await webrtcService.addIceCandidateForUser(peerId, signalData);
            }
            break;
          }

          // 1:1 Direct Call Signaling
          if (signalType === 'offer') {
            if (activeCallRef.current) {
              const answer = await webrtcService.handleOfferAndCreateAnswer(signalData);
              const callerId = msg.caller?.id || msg.caller?.userId;
              sendSignal(msg.callId, callerId, 'answer', answer);
            } else {
              // Queue offer until user hits "Accept"
              pendingOfferRef.current = signalData;
            }
          } else if (signalType === 'answer') {
            await webrtcService.handleAnswer(signalData);
          } else if (signalType === 'ice-candidate') {
            await webrtcService.addIceCandidate(signalData);
          }
          break;
        }

        default:
          break;
      }
    });

    return () => {
      if (typeof unsubscribe === 'function') unsubscribe();
      cleanupCallState();
    };
  }, [currentUserId]);

  // Cleanup active call if user closes tab or refreshes page
  useEffect(() => {
    const handleBeforeUnload = () => {
      const current = activeCallRef.current;
      if (current?.callId) {
        try {
          const token = localStorage.getItem('token');
          const headers = { 'Content-Type': 'application/json' };
          if (token) headers['Authorization'] = `Bearer ${token}`;
          fetch(`/api/calls/${current.callId}/end`, {
            method: 'POST',
            headers,
            keepalive: true,
          });
        } catch {
          // ignore
        }
      }
    };

    window.addEventListener('beforeunload', handleBeforeUnload);
    return () => window.removeEventListener('beforeunload', handleBeforeUnload);
  }, []);

  const value = {
    incomingCall,
    activeCall,
    localStream,
    remoteStream,
    remoteStreams,
    groupParticipants,
    isMuted,
    isVideoOff,
    isScreenSharing,
    callDuration,
    isMinimized,
    callStatusText,
    startCall,
    startGroupCall,
    acceptCall,
    rejectCall,
    endCall,
    toggleMute,
    toggleVideo,
    toggleScreenShare,
    toggleMinimize,
  };

  return <CallContext.Provider value={value}>{children}</CallContext.Provider>;
};

export const useCall = () => {
  const context = useContext(CallContext);
  if (!context) {
    return {
      incomingCall: null,
      activeCall: null,
      localStream: null,
      remoteStream: null,
      remoteStreams: {},
      groupParticipants: [],
      isMuted: false,
      isVideoOff: false,
      isScreenSharing: false,
      callDuration: 0,
      isMinimized: false,
      callStatusText: '',
      startCall: () => {},
      startGroupCall: () => {},
      acceptCall: () => {},
      rejectCall: () => {},
      endCall: () => {},
      toggleMute: () => {},
      toggleVideo: () => {},
      toggleScreenShare: () => {},
      toggleMinimize: () => {},
    };
  }
  return context;
};

export default CallContext;
